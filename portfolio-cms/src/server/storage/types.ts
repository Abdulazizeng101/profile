export type PutOptions = {
  contentType: string;
  /** Defaults to one year, immutable: every upload gets a new random key. */
  cacheControl?: string;
  contentDisposition?: string;
};

export type StoredObject = {
  body: Buffer;
  contentType: string;
};

export interface StorageDriver {
  readonly name: "local" | "s3";
  put(key: string, body: Buffer, options: PutOptions): Promise<void>;
  get(key: string): Promise<StoredObject | null>;
  delete(keys: string[]): Promise<void>;
  /** Absolute or root-relative URL a browser can load the object from. */
  publicUrl(key: string): string;
}

export const IMMUTABLE_CACHE = "public, max-age=31536000, immutable";

/**
 * Storage keys are generated by the server only. This pattern is enforced
 * everywhere a key is read back so a key can never escape the storage root.
 */
export const STORAGE_KEY_PATTERN = /^(images|documents)\/[a-f0-9-]{36}(\/[a-z0-9-]{1,40})?\.(webp|pdf)$/;

export function assertValidKey(key: string): void {
  if (!STORAGE_KEY_PATTERN.test(key)) throw new Error(`Invalid storage key: ${key}`);
}
